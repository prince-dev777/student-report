// Generate attendance for last 30 days
function generateAttendance(students) {
  const records = [];
  const today = new Date();

  for (let dayOffset = 30; dayOffset >= 0; dayOffset--) {
    const date = new Date(today);
    date.setDate(date.getDate() - dayOffset);

    // Skip Sundays
    if (date.getDay() === 0) continue;

    const dateStr = date.toISOString().split('T')[0];

    students.forEach((student) => {
      if (student.status === 'inactive') return;

      const random = Math.random();
      let status, entryTime, exitTime;

      if (random < 0.78) {
        status = 'present';
        const entryHour = 5 + Math.floor(Math.random() * 3);
        const entryMin = Math.floor(Math.random() * 30);
        entryTime = `${String(entryHour).padStart(2, '0')}:${String(entryMin).padStart(2, '0')}`;

        const exitHour = entryHour + 2 + Math.floor(Math.random() * 2);
        const exitMin = Math.floor(Math.random() * 60);
        exitTime = `${String(exitHour).padStart(2, '0')}:${String(exitMin).padStart(2, '0')}`;
      } else if (random < 0.88) {
        status = 'late';
        const entryHour = 8 + Math.floor(Math.random() * 2);
        const entryMin = Math.floor(Math.random() * 60);
        entryTime = `${String(entryHour).padStart(2, '0')}:${String(entryMin).padStart(2, '0')}`;

        const exitHour = entryHour + 2;
        const exitMin = Math.floor(Math.random() * 60);
        exitTime = `${String(exitHour).padStart(2, '0')}:${String(exitMin).padStart(2, '0')}`;
      } else {
        status = 'absent';
        entryTime = null;
        exitTime = null;
      }

      records.push({
        id: `ATT-${dateStr}-${student.id}`,
        studentId: student.id,
        date: dateStr,
        status,
        entryTime,
        exitTime,
        smsSent: status !== 'absent',
      });
    });
  }

  return records;
}

// Generate test results
function generateTests(students) {
  const testDefinitions = [
    { id: 'TEST001', name: 'Weekly Test 1', subject: 'Physics', date: '2025-05-05', totalMarks: 100, batch: 'batch-1' },
    { id: 'TEST002', name: 'Weekly Test 2', subject: 'Chemistry', date: '2025-05-12', totalMarks: 100, batch: 'batch-1' },
    { id: 'TEST003', name: 'Monthly Test - May', subject: 'Mathematics', date: '2025-05-20', totalMarks: 150, batch: 'batch-1' },
    { id: 'TEST004', name: 'NEET Mock 1', subject: 'Biology', date: '2025-05-15', totalMarks: 200, batch: 'batch-2' },
    { id: 'TEST005', name: 'MHCET Quiz 1', subject: 'Mathematics', date: '2025-05-18', totalMarks: 50, batch: 'batch-3' },
  ];

  const testResults = [];

  testDefinitions.forEach((test) => {
    const batchStudents = students.filter((s) => s.batch === test.batch && s.status === 'active');
    const results = [];

    batchStudents.forEach((student) => {
      const percentage = 35 + Math.random() * 60; // 35% to 95%
      const marks = Math.round((percentage / 100) * test.totalMarks);
      results.push({
        studentId: student.id,
        marks,
        percentage: Math.round(percentage * 10) / 10,
      });
    });

    // Sort by marks descending and assign ranks
    results.sort((a, b) => b.marks - a.marks);
    results.forEach((r, idx) => {
      r.rank = idx + 1;
      testResults.push({
        id: `RES-${test.id}-${r.studentId}`,
        testId: test.id,
        studentId: r.studentId,
        marks: r.marks,
        totalMarks: test.totalMarks,
        percentage: r.percentage,
        rank: r.rank,
        totalStudents: results.length,
        smsSent: true,
      });
    });
  });

  return { tests: testDefinitions, results: testResults };
}

// Generate SMS history
function generateSMSHistory(students, attendance, testResults) {
  const smsHistory = [];
  let smsId = 1;

  // Attendance SMS (last 5 days only for brevity)
  const recentAttendance = attendance.slice(-70);
  recentAttendance.forEach((att) => {
    if (att.status === 'absent') return;
    const student = students.find((s) => s.id === att.studentId);
    if (!student) return;

    if (att.entryTime) {
      smsHistory.push({
        id: `SMS${String(smsId++).padStart(4, '0')}`,
        type: 'attendance-entry',
        studentId: student.id,
        parentPhone: student.parentPhone,
        message: `Namaste ${student.parentName} ji, aapka bachha ${student.name} aaj ${att.date} ko ${att.entryTime} par coaching me aa gaya hai. - Career Xone Pro`,
        timestamp: `${att.date}T${att.entryTime}:00`,
        status: Math.random() > 0.05 ? 'delivered' : 'sent',
      });
    }

    if (att.exitTime) {
      smsHistory.push({
        id: `SMS${String(smsId++).padStart(4, '0')}`,
        type: 'attendance-exit',
        studentId: student.id,
        parentPhone: student.parentPhone,
        message: `Namaste ${student.parentName} ji, aapka bachha ${student.name} aaj ${att.date} ko ${att.exitTime} par coaching se nikal gaya hai. - Career Xone Pro`,
        timestamp: `${att.date}T${att.exitTime}:00`,
        status: 'delivered',
      });
    }
  });

  // Test result SMS
  testResults.forEach((result) => {
    const student = students.find((s) => s.id === result.studentId);
    if (!student) return;

    smsHistory.push({
      id: `SMS${String(smsId++).padStart(4, '0')}`,
      type: 'test-result',
      studentId: student.id,
      parentPhone: student.parentPhone,
      message: `Namaste ${student.parentName} ji, ${student.name} ka test result: Marks ${result.marks}/${result.totalMarks} (${result.percentage}%), Rank: ${result.rank}/${result.totalStudents}. - Career Xone Pro`,
      timestamp: `${new Date().toISOString().split('T')[0]}T10:00:00`,
      status: 'delivered',
    });
  });

  return smsHistory;
}

